-- Schema para o perfil h2 (copia do 01_DDL_caminhoseguro.sql, sem os DROP TABLE).
-- ---------------------------------------------------------------------
-- 1) BAIRRO: permite levar a solução para outros bairros (escala).
-- ---------------------------------------------------------------------
CREATE TABLE T_CS_BAIRRO (
    id_bairro    NUMBER(6)     GENERATED BY DEFAULT AS IDENTITY,
    nm_bairro    VARCHAR2(60)  NOT NULL,
    nm_cidade    VARCHAR2(60)  NOT NULL,
    sg_uf        CHAR(2)       NOT NULL
);

-- ---------------------------------------------------------------------
-- 2) TIPO_LOCAL: domínio dos tipos de ponto do mapa (UBS, mercado...).
-- ---------------------------------------------------------------------
CREATE TABLE T_CS_TIPO_LOCAL (
    id_tipo_local NUMBER(4)    GENERATED BY DEFAULT AS IDENTITY,
    ds_tipo_local VARCHAR2(40) NOT NULL
);

-- ---------------------------------------------------------------------
-- 3) LOCAL: pontos do bairro (nós do grafo de rotas).
-- ---------------------------------------------------------------------
CREATE TABLE T_CS_LOCAL (
    id_local        NUMBER(8)     GENERATED BY DEFAULT AS IDENTITY,
    id_bairro       NUMBER(6)     NOT NULL,
    id_tipo_local   NUMBER(4)     NOT NULL,
    nm_local        VARCHAR2(80)  NOT NULL,
    ds_endereco     VARCHAR2(120),
    nr_latitude     NUMBER(9,6),
    nr_longitude    NUMBER(9,6),
    st_ponto_apoio  CHAR(1)       DEFAULT 'N' NOT NULL
);

-- ---------------------------------------------------------------------
-- 4) TRECHO: ligação entre dois locais (arestas do grafo de rotas).
-- ---------------------------------------------------------------------
CREATE TABLE T_CS_TRECHO (
    id_trecho            NUMBER(8)    GENERATED BY DEFAULT AS IDENTITY,
    id_local_origem      NUMBER(8)    NOT NULL,
    id_local_destino     NUMBER(8)    NOT NULL,
    nr_tempo_min         NUMBER(4)    NOT NULL,
    nr_risco             NUMBER(2)    NOT NULL,
    st_acessivel         CHAR(1)      DEFAULT 'S' NOT NULL,
    nr_declividade_pct   NUMBER(4,1),
    nr_largura_calcada_m NUMBER(4,2)
);

-- ---------------------------------------------------------------------
-- 5) USUARIO: moradores, cuidadores e agentes (dados SIMULADOS).
-- ---------------------------------------------------------------------
CREATE TABLE T_CS_USUARIO (
    id_usuario   NUMBER(8)     GENERATED BY DEFAULT AS IDENTITY,
    nm_usuario   VARCHAR2(80)  NOT NULL,
    ds_email     VARCHAR2(120) NOT NULL,
    tp_perfil    VARCHAR2(12)  NOT NULL,
    dt_cadastro  DATE          DEFAULT SYSDATE NOT NULL
);

-- ---------------------------------------------------------------------
-- 6) TIPO_OCORRENCIA: domínio dos problemas de calçada.
-- ---------------------------------------------------------------------
CREATE TABLE T_CS_TIPO_OCORRENCIA (
    id_tipo_ocorrencia   NUMBER(4)    GENERATED BY DEFAULT AS IDENTITY,
    ds_tipo_ocorrencia   VARCHAR2(50) NOT NULL,
    nr_gravidade_padrao  NUMBER(1)    NOT NULL
);

-- ---------------------------------------------------------------------
-- 7) OCORRENCIA: problema registrado pela comunidade em um trecho.
-- ---------------------------------------------------------------------
CREATE TABLE T_CS_OCORRENCIA (
    id_ocorrencia       NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
    id_trecho           NUMBER(8)      NOT NULL,
    id_usuario          NUMBER(8)      NOT NULL,
    id_tipo_ocorrencia  NUMBER(4)      NOT NULL,
    ds_ocorrencia       VARCHAR2(400),
    nr_gravidade        NUMBER(1)      NOT NULL,
    st_ocorrencia       VARCHAR2(12)   DEFAULT 'ABERTA' NOT NULL,
    dt_registro         DATE           DEFAULT SYSDATE NOT NULL,
    dt_resolucao        DATE
);

-- ---------------------------------------------------------------------
-- 8) ROTA_CONSULTA: histórico de rotas pedidas (indicador de impacto).
-- ---------------------------------------------------------------------
CREATE TABLE T_CS_ROTA_CONSULTA (
    id_consulta       NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
    id_usuario        NUMBER(8)    NOT NULL,
    id_local_origem   NUMBER(8)    NOT NULL,
    id_local_destino  NUMBER(8)    NOT NULL,
    tp_criterio       VARCHAR2(10) NOT NULL,
    nr_tempo_total    NUMBER(4),
    dt_consulta       DATE         DEFAULT SYSDATE NOT NULL
);

-- =====================================================================
-- CONSTRAINTS (ALTER TABLE): chaves primárias
-- =====================================================================
ALTER TABLE T_CS_BAIRRO          ADD CONSTRAINT PK_CS_BAIRRO          PRIMARY KEY (id_bairro);
ALTER TABLE T_CS_TIPO_LOCAL      ADD CONSTRAINT PK_CS_TIPO_LOCAL      PRIMARY KEY (id_tipo_local);
ALTER TABLE T_CS_LOCAL           ADD CONSTRAINT PK_CS_LOCAL           PRIMARY KEY (id_local);
ALTER TABLE T_CS_TRECHO          ADD CONSTRAINT PK_CS_TRECHO          PRIMARY KEY (id_trecho);
ALTER TABLE T_CS_USUARIO         ADD CONSTRAINT PK_CS_USUARIO         PRIMARY KEY (id_usuario);
ALTER TABLE T_CS_TIPO_OCORRENCIA ADD CONSTRAINT PK_CS_TIPO_OCORRENCIA PRIMARY KEY (id_tipo_ocorrencia);
ALTER TABLE T_CS_OCORRENCIA      ADD CONSTRAINT PK_CS_OCORRENCIA      PRIMARY KEY (id_ocorrencia);
ALTER TABLE T_CS_ROTA_CONSULTA   ADD CONSTRAINT PK_CS_ROTA_CONSULTA   PRIMARY KEY (id_consulta);

-- =====================================================================
-- CONSTRAINTS: únicas (UNIQUE)
-- =====================================================================
ALTER TABLE T_CS_BAIRRO          ADD CONSTRAINT UN_CS_BAIRRO_NOME     UNIQUE (nm_bairro, nm_cidade, sg_uf);
ALTER TABLE T_CS_TIPO_LOCAL      ADD CONSTRAINT UN_CS_TIPO_LOCAL_DS   UNIQUE (ds_tipo_local);
ALTER TABLE T_CS_LOCAL           ADD CONSTRAINT UN_CS_LOCAL_NOME      UNIQUE (id_bairro, nm_local);
ALTER TABLE T_CS_TRECHO          ADD CONSTRAINT UN_CS_TRECHO_PAR      UNIQUE (id_local_origem, id_local_destino);
ALTER TABLE T_CS_USUARIO         ADD CONSTRAINT UN_CS_USUARIO_EMAIL   UNIQUE (ds_email);
ALTER TABLE T_CS_TIPO_OCORRENCIA ADD CONSTRAINT UN_CS_TIPO_OCOR_DS    UNIQUE (ds_tipo_ocorrencia);

-- =====================================================================
-- CONSTRAINTS: verificação (CHECK)
-- =====================================================================
ALTER TABLE T_CS_LOCAL  ADD CONSTRAINT CK_CS_LOCAL_APOIO   CHECK (st_ponto_apoio IN ('S','N'));
ALTER TABLE T_CS_LOCAL  ADD CONSTRAINT CK_CS_LOCAL_LAT     CHECK (nr_latitude  BETWEEN -90  AND 90);
ALTER TABLE T_CS_LOCAL  ADD CONSTRAINT CK_CS_LOCAL_LON     CHECK (nr_longitude BETWEEN -180 AND 180);
ALTER TABLE T_CS_TRECHO ADD CONSTRAINT CK_CS_TRECHO_TEMPO  CHECK (nr_tempo_min > 0);
ALTER TABLE T_CS_TRECHO ADD CONSTRAINT CK_CS_TRECHO_RISCO  CHECK (nr_risco BETWEEN 0 AND 10);
ALTER TABLE T_CS_TRECHO ADD CONSTRAINT CK_CS_TRECHO_ACESS  CHECK (st_acessivel IN ('S','N'));
ALTER TABLE T_CS_TRECHO ADD CONSTRAINT CK_CS_TRECHO_LOCAIS CHECK (id_local_origem <> id_local_destino);
ALTER TABLE T_CS_TRECHO ADD CONSTRAINT CK_CS_TRECHO_LARG   CHECK (nr_largura_calcada_m > 0);
ALTER TABLE T_CS_USUARIO ADD CONSTRAINT CK_CS_USUARIO_PERFIL
    CHECK (tp_perfil IN ('IDOSO','PCD','CUIDADOR','MORADOR','AGENTE'));
ALTER TABLE T_CS_USUARIO ADD CONSTRAINT CK_CS_USUARIO_EMAIL CHECK (ds_email LIKE '%_@_%._%');
ALTER TABLE T_CS_TIPO_OCORRENCIA ADD CONSTRAINT CK_CS_TIPO_OCOR_GRAV CHECK (nr_gravidade_padrao BETWEEN 1 AND 5);
ALTER TABLE T_CS_OCORRENCIA ADD CONSTRAINT CK_CS_OCOR_GRAV   CHECK (nr_gravidade BETWEEN 1 AND 5);
ALTER TABLE T_CS_OCORRENCIA ADD CONSTRAINT CK_CS_OCOR_STATUS CHECK (st_ocorrencia IN ('ABERTA','EM_ANALISE','RESOLVIDA'));
ALTER TABLE T_CS_OCORRENCIA ADD CONSTRAINT CK_CS_OCOR_DATAS  CHECK (dt_resolucao IS NULL OR dt_resolucao >= dt_registro);
ALTER TABLE T_CS_ROTA_CONSULTA ADD CONSTRAINT CK_CS_ROTA_CRITERIO CHECK (tp_criterio IN ('RAPIDA','SEGURA','ACESSIVEL'));
ALTER TABLE T_CS_ROTA_CONSULTA ADD CONSTRAINT CK_CS_ROTA_LOCAIS   CHECK (id_local_origem <> id_local_destino);

-- =====================================================================
-- CONSTRAINTS: chaves estrangeiras (relacionamentos)
-- =====================================================================
-- BAIRRO 1:N LOCAL
ALTER TABLE T_CS_LOCAL ADD CONSTRAINT FK_CS_LOCAL_BAIRRO
    FOREIGN KEY (id_bairro) REFERENCES T_CS_BAIRRO (id_bairro);
-- TIPO_LOCAL 1:N LOCAL
ALTER TABLE T_CS_LOCAL ADD CONSTRAINT FK_CS_LOCAL_TIPO
    FOREIGN KEY (id_tipo_local) REFERENCES T_CS_TIPO_LOCAL (id_tipo_local);
-- LOCAL 1:N TRECHO (como origem) e LOCAL 1:N TRECHO (como destino)
ALTER TABLE T_CS_TRECHO ADD CONSTRAINT FK_CS_TRECHO_ORIGEM
    FOREIGN KEY (id_local_origem) REFERENCES T_CS_LOCAL (id_local);
ALTER TABLE T_CS_TRECHO ADD CONSTRAINT FK_CS_TRECHO_DESTINO
    FOREIGN KEY (id_local_destino) REFERENCES T_CS_LOCAL (id_local);
-- TRECHO 1:N OCORRENCIA
ALTER TABLE T_CS_OCORRENCIA ADD CONSTRAINT FK_CS_OCOR_TRECHO
    FOREIGN KEY (id_trecho) REFERENCES T_CS_TRECHO (id_trecho);
-- USUARIO 1:N OCORRENCIA
ALTER TABLE T_CS_OCORRENCIA ADD CONSTRAINT FK_CS_OCOR_USUARIO
    FOREIGN KEY (id_usuario) REFERENCES T_CS_USUARIO (id_usuario);
-- TIPO_OCORRENCIA 1:N OCORRENCIA
ALTER TABLE T_CS_OCORRENCIA ADD CONSTRAINT FK_CS_OCOR_TIPO
    FOREIGN KEY (id_tipo_ocorrencia) REFERENCES T_CS_TIPO_OCORRENCIA (id_tipo_ocorrencia);
-- USUARIO 1:N ROTA_CONSULTA
ALTER TABLE T_CS_ROTA_CONSULTA ADD CONSTRAINT FK_CS_ROTA_USUARIO
    FOREIGN KEY (id_usuario) REFERENCES T_CS_USUARIO (id_usuario);
-- LOCAL 1:N ROTA_CONSULTA (origem e destino)
ALTER TABLE T_CS_ROTA_CONSULTA ADD CONSTRAINT FK_CS_ROTA_ORIGEM
    FOREIGN KEY (id_local_origem) REFERENCES T_CS_LOCAL (id_local);
ALTER TABLE T_CS_ROTA_CONSULTA ADD CONSTRAINT FK_CS_ROTA_DESTINO
    FOREIGN KEY (id_local_destino) REFERENCES T_CS_LOCAL (id_local);
